using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace AutopilotMonitor.Agent.V2.Core.Monitoring.Runtime
{
    /// <summary>
    /// Which bootstrap installed this agent, read from the bootstrap scripts' own logs next to the
    /// agent log. The scripts cannot report it themselves (they run before any agent exists), and
    /// passing a version to <c>--install</c> would only ever cover installers released after that
    /// change -- the old installers still assigned in Intune are exactly the ones worth counting.
    /// <list type="bullet">
    ///   <item><c>bootstrap-script.log</c> (<c>bootstrap_agent.log</c> up to installer v2.3, before
    ///   the log rename of 2026-08-18): <c>Bootstrap script version: vX.Y</c>, written by every
    ///   installer run since 2026-04-09. A log without that line means an older installer.</item>
    ///   <item><c>bootstrap-loader.log</c> (Intune) / <c>bootstrap-msi.log</c> (MSI,
    ///   <c>msi-bootstrap.log</c> before 2026-08-18): <c>bootstrap loader vX.Y started</c>, written by
    ///   every loader since v1.0. The MSI's own downloader, which the loader replaced on 2026-09-08,
    ///   writes no version.</item>
    ///   <item><c>oobe_bootstrap.log</c>: the OOBE go-script (generated by the backend, no version).</item>
    /// </list>
    /// Only the version number is extracted; the loader line also names the account, which is
    /// never read out. Observational only, and it never throws: an unreadable log reads as absent.
    /// </summary>
    internal static class BootstrapProvenanceReader
    {
        internal const string InstallerLogName = "bootstrap-script.log";
        internal const string LoaderLogName = "bootstrap-loader.log";
        internal const string MsiLoaderLogName = "bootstrap-msi.log";
        internal const string OobeLogName = "oobe_bootstrap.log";

        // Names before the log rename of 2026-08-18; copies of those scripts are still assigned.
        internal const string LegacyInstallerLogName = "bootstrap_agent.log";
        internal const string LegacyMsiLoaderLogName = "msi-bootstrap.log";

        // The logs grow across runs; the last run's lines sit at the end. One run writes a few KB.
        private const int TailBytes = 64 * 1024;

        private static readonly Regex InstallerVersionLine = new Regex(
            @"Bootstrap script version: v(?<v>\d+(?:\.\d+){0,3})\b", RegexOptions.CultureInvariant);

        private static readonly Regex LoaderStartLine = new Regex(
            @"bootstrap loader v(?<v>\d+(?:\.\d+){0,3}) started\b", RegexOptions.CultureInvariant);

        public static BootstrapProvenance Read(string logDirectory)
        {
            try
            {
                var installerLog = ReadTail(MostRecentlyWritten(logDirectory, InstallerLogName, LegacyInstallerLogName));

                // Intune loader and MSI loader write separate files; every name but the Intune
                // loader's is the MSI's.
                var loaderPath = MostRecentlyWritten(logDirectory, LoaderLogName, MsiLoaderLogName, LegacyMsiLoaderLogName);
                var loaderChannel = loaderPath == null ? null
                    : string.Equals(Path.GetFileName(loaderPath), LoaderLogName, StringComparison.OrdinalIgnoreCase) ? "loader" : "msi";

                return new BootstrapProvenance(
                    scriptLogPresent: installerLog != null,
                    scriptVersion: LastVersion(installerLog, InstallerVersionLine),
                    loaderLog: loaderChannel,
                    loaderVersion: LastVersion(ReadTail(loaderPath), LoaderStartLine),
                    oobeLogPresent: File.Exists(Path.Combine(logDirectory, OobeLogName)));
            }
            catch
            {
                return BootstrapProvenance.Unknown;
            }
        }

        /// <summary>
        /// The most recently written of the named logs that exist, or null. On a device with
        /// several, it belongs to the bootstrap that ran last.
        /// </summary>
        private static string MostRecentlyWritten(string directory, params string[] names) =>
            names.Select(name => Path.Combine(directory, name))
                .Where(path => File.Exists(path))
                .OrderByDescending(path => File.GetLastWriteTimeUtc(path))
                .FirstOrDefault();

        internal static string LastVersion(string text, Regex line)
        {
            if (string.IsNullOrEmpty(text)) return null;
            string version = null;
            foreach (Match match in line.Matches(text))
                version = match.Groups["v"].Value;
            return version;
        }

        /// <summary>The last <see cref="TailBytes"/> of the file, or null when it is missing or unreadable.</summary>
        private static string ReadTail(string path)
        {
            try
            {
                if (!File.Exists(path)) return null;
                using (var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete))
                {
                    var start = Math.Max(0, stream.Length - TailBytes);
                    stream.Seek(start, SeekOrigin.Begin);
                    var buffer = new byte[stream.Length - start];
                    var read = 0;
                    while (read < buffer.Length)
                    {
                        var n = stream.Read(buffer, read, buffer.Length - read);
                        if (n == 0) break;
                        read += n;
                    }
                    // The scripts write ASCII (their own pure-ASCII rule); UTF-8 decodes it either way.
                    return Encoding.UTF8.GetString(buffer, 0, read);
                }
            }
            catch
            {
                return null;
            }
        }
    }

    /// <summary>What <see cref="BootstrapProvenanceReader"/> found; null fields were not found.</summary>
    internal sealed class BootstrapProvenance
    {
        public static readonly BootstrapProvenance Unknown = new BootstrapProvenance(false, null, null, null, false);

        public BootstrapProvenance(bool scriptLogPresent, string scriptVersion, string loaderLog, string loaderVersion, bool oobeLogPresent)
        {
            ScriptLogPresent = scriptLogPresent;
            ScriptVersion = scriptVersion;
            LoaderLog = loaderLog;
            LoaderVersion = loaderVersion;
            OobeLogPresent = oobeLogPresent;
        }

        public bool ScriptLogPresent { get; }
        public string ScriptVersion { get; }
        public string LoaderLog { get; }
        public string LoaderVersion { get; }
        public bool OobeLogPresent { get; }

        /// <summary>
        /// Adds the <c>agent_started</c> keys. Version and loader keys only when found, so a
        /// missing key always means "not found" and never an empty string.
        /// </summary>
        public void AddTo(IDictionary<string, object> data)
        {
            data["bootstrapScriptLogPresent"] = ScriptLogPresent;
            if (ScriptVersion != null) data["bootstrapScriptVersion"] = ScriptVersion;
            if (LoaderLog != null) data["bootstrapLoaderLog"] = LoaderLog;
            if (LoaderVersion != null) data["bootstrapLoaderVersion"] = LoaderVersion;
            data["oobeBootstrapLogPresent"] = OobeLogPresent;
        }
    }
}
