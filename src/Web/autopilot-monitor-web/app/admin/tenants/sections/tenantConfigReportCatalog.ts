/** One rendered row: where its value and default come from, resolved against a response. */
export interface CataloguedRuntimeRow {
  key: string;
  row: RuntimeRow;
  value: (r: AgentConfigResponse) => unknown;
  default: unknown;
}

export interface CataloguedTenantRow {
  key: keyof TenantConfiguration;
  row: TenantRow;
  default: unknown;
}

function tenantRows(): Array<{ section: TenantSection; rows: CataloguedTenantRow[] }> {
  const bySection = new Map<TenantSection, CataloguedTenantRow[]>(TENANT_SECTIONS.map((s) => [s, []]));
  for (const [key, spec] of Object.entries(TENANT_FIELDS) as Array<[keyof TenantConfiguration, TenantRow | Excluded]>) {
    if (isExcluded(spec)) continue;
    bySection.get(spec.section)!.push({ key, row: spec, default: TENANT_DEFAULTS[key] });
  }
  return TENANT_SECTIONS.map((section) => ({ section, rows: bySection.get(section)! }));
}

function runtimeRows(): Array<{ section: RuntimeSection; rows: CataloguedRuntimeRow[] }> {
  const bySection = new Map<RuntimeSection, CataloguedRuntimeRow[]>(RUNTIME_SECTIONS.map((s) => [s, []]));
  const add = (key: string, spec: RuntimeRow | Excluded, value: (r: AgentConfigResponse) => unknown, def: unknown) => {
    if (isExcluded(spec)) return;
    bySection.get(spec.section)!.push({ key, row: spec, value, default: def });
  };
  for (const [key, spec] of Object.entries(RUNTIME_FIELDS) as Array<[keyof AgentConfigResponse, RuntimeRow | Excluded]>) {
    add(key, spec, (r) => r[key], RUNTIME_DEFAULTS[key]);
  }
  for (const [key, spec] of Object.entries(COLLECTOR_FIELDS) as Array<[keyof CollectorConfiguration, RuntimeRow | Excluded]>) {
    add(`collectors.${key}`, spec, (r) => r.collectors?.[key], COLLECTOR_DEFAULTS[key]);
  }
  for (const [key, spec] of Object.entries(ANALYZER_FIELDS) as Array<[keyof AnalyzerConfiguration, RuntimeRow | Excluded]>) {
    add(`analyzers.${key}`, spec, (r) => r.analyzers?.[key], ANALYZER_DEFAULTS[key]);
  }
  return RUNTIME_SECTIONS.map((section) => ({ section, rows: bySection.get(section)! }));
}

