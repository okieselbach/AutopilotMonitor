/**
 * How a value is rendered. `secret` never shows the value, only whether one is set;
 * `count` shows the length of a list.
 */
export type RowKind = "value" | "date" | "masked" | "secret" | "count";

interface RowBase {
  label: string;
  kind?: RowKind;
  /** Informational rows (reasons, timestamps, identities, secrets) are never marked "custom". */
  informational?: true;
}

export interface TenantRow extends RowBase {
  section: TenantSection;
}

/** Which knob a runtime value is resolved from (AgentConfigResolver.Build). */
export type RuntimeSource = "tenant" | "global" | "entitlement" | "fixed";

export interface RuntimeRow extends RowBase {
  section: RuntimeSection;
  source: RuntimeSource;
}

export interface Excluded {
  excluded: string;
}

export const isExcluded = <T extends object>(spec: T | Excluded): spec is Excluded =>
  "excluded" in spec;

