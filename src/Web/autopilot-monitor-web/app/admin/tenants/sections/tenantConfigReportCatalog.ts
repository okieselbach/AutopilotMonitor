/**
 * Row catalog for the Tenant Config Report (admin/tenants/config-report).
 *
 * Both halves of the report are exhaustive over the generated wire types: `TENANT_FIELDS`
 * over every key of `TenantConfiguration` (GET config/{tenantId}) and `RUNTIME_FIELDS` /
 * `COLLECTOR_FIELDS` / `ANALYZER_FIELDS` over every key of `AgentConfigResponse` and its two
 * sub-objects (GET config/{tenantId}/effective-agent-config — the backend's own derivation,
 * nothing is re-computed here). A key is either rendered (a row with section and label) or
 * excluded with a reason — nothing can be silently forgotten: a new C# property forces the
 * wire-type regeneration (SharedManifestParityTests) and `tsc` then fails here until the key
 * is catalogued.
 *
 * The "custom" highlight compares a value against the C# initializer of the same property,
 * which the shared manifest carries as `defaults` (generated by the same test) — no
 * hand-copied default anywhere in this file.
 */
